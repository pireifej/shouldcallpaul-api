router.get('/getDailyDevotional', async (req, res) => {
  try {
    const today = new Date().toLocaleDateString('en-CA', { timeZone: 'America/New_York' });
    let result = await pool.query(
      'SELECT * FROM public.daily_devotional WHERE date = $1 AND lang = $2',
      [today, 'en']
    );

    // Today's article is missing — auto-generate it now (first caller triggers it, everyone else benefits)
    if (result.rows.length === 0) {
      console.log(`📖 No devotional for ${today} — auto-generating on demand...`);
      try {
        await generateDailyDevotional(new Date());
        result = await pool.query(
          'SELECT * FROM public.daily_devotional WHERE date = $1 AND lang = $2',
          [today, 'en']
        );
        // If it's past 8 AM Eastern (12:00 PM UTC), the scheduled notification
        // already missed — send it now as a catch-up for all users
        const utcHour = new Date().getUTCHours();
        if (utcHour >= 12) {
          sendDailyDevotionalNotification('catch-up after on-demand generation').catch(e =>
            console.error('Catch-up notification failed:', e.message)
          );
        }
      } catch (genErr) {
        console.error('On-demand devotional generation failed:', genErr.message);
        // Generation failed — fall back to most recent so the app still works
        result = await pool.query(
          'SELECT * FROM public.daily_devotional ORDER BY date DESC LIMIT 1'
        );
      }
    }

    if (result.rows.length === 0) {
      return res.json({ error: 1, result: 'No devotional available yet.' });
    }

    const row = result.rows[0];
    row.date = new Date(row.date).toISOString().slice(0, 10);
    res.json({ error: 0, result: row });
  } catch (error) {
    console.error('getDailyDevotional error:', error);
    res.status(500).json({ error: 1, result: 'Internal server error' });
  }
});

